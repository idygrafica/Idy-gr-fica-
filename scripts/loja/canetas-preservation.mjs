import assert from 'node:assert/strict';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {products,categories} from '../../assets/loja/catalog.js';
const base=JSON.parse(readFileSync('scripts/loja/canetas-baseline.json','utf8'));
const mutable=new Set(['assets/loja/app.js','assets/loja/cart.js','assets/loja/catalog.js','scripts/loja/cart.test.mjs','scripts/loja/browser.mjs']);
const hash=b=>createHash('sha1').update(Buffer.from(`blob ${b.length}\0`)).update(b).digest('hex');
for(const f of base.files)if(!mutable.has(f.path))assert.equal(hash(readFileSync(f.path)),f.sha,'Arquivo fora do escopo alterado: '+f.path);
const source=execFileSync('git',['show',base.commit+':assets/loja/catalog.js']);
const before=await import('data:text/javascript;base64,'+source.toString('base64'));
assert.deepEqual(products.filter(p=>p.id!=='canetas'),before.products.filter(p=>p.id!=='canetas'),'Outro produto alterado');
assert.deepEqual(categories,before.categories,'Categorias alteradas');
assert.equal(products.find(p=>p.id==='canetas').photo,before.products.find(p=>p.id==='canetas').photo);
const allowedNew=['scripts/loja/canetas','scripts/loja/browser-canetas.mjs','.github/workflows/canetas-precos.yml'];
const diff=execFileSync('git',['diff','--name-only',base.commit,'HEAD'],{encoding:'utf8'}).trim().split('\n').filter(Boolean);
for(const f of diff)assert(mutable.has(f)||allowedNew.some(p=>f.startsWith(p)),'Mudança fora do escopo: '+f);
mkdirSync('.preview/canetas',{recursive:true});
const report={base:base.commit,protectedFiles:base.files.length-mutable.size,otherProductsUnchanged:7,approvedImageUnchanged:true,layoutFilesUnchanged:true,homepageUnchanged:true,aiProjectModified:false};
writeFileSync('.preview/canetas/preservation.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
